//! #337: everything host-specific comes in through the host file (`src/host.rs`, `--config`).
//! `tests/fixtures/host/` is a host of two adapters and one rebound name; without a file the host
//! is empty and an import of a module not compiled in the same call is refused.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Arc;

const APP: &str = include_str!("fixtures/host/app.ts");

fn fixture() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/host/ts2py.toml")
}

fn host() -> Arc<ts2py::Host> {
    Arc::new(ts2py::Host::load(&fixture()).unwrap_or_else(|e| panic!("{e}")))
}

fn options(host: Arc<ts2py::Host>) -> ts2py::Options {
    ts2py::Options {
        runtime_module: Some("._ts2py_runtime".to_string()),
        host,
        ..ts2py::Options::default()
    }
}

fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("ts2py-host-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn without_a_host_every_import_and_process_global_is_refused() {
    let lines = ts2py::compile(APP, "src/app.ts", &options(Arc::default()))
        .expect_err("an empty host declares no adapter");
    assert_eq!(
        lines,
        [
            "src/app.ts:1:10: unsupported import of cmpCp from ./helpers.js: no compiled module and no declared adapter: cmpCp",
            "src/app.ts:1:17: unsupported import of twice from ./helpers.js: no compiled module and no declared adapter: twice",
            "src/app.ts:12:10: unsupported process.env read: no declared adapter: process.env.HOME",
        ]
    );
    let plain = ts2py::compile(
        "export const N = 1;\n",
        "src/n.ts",
        &options(Arc::default()),
    )
    .unwrap();
    assert!(plain.starts_with("# Generated by ts2py from src/n.ts. DO NOT EDIT"));
    assert!(plain.contains("\"\"\"Generated from `src/n.ts` by ts2py; the TypeScript"));
}

#[test]
fn the_host_file_supplies_the_names_the_rows_and_the_rebound_names() {
    let host = host();
    assert_eq!(host.generator, "ts2py (test host)");
    assert_eq!(host.adapters.rows.len(), 2);
    // process.env has no row in the fixture either: still a refusal, never a panic.
    let lines = ts2py::compile(APP, "src/app.ts", &options(host.clone())).unwrap_err();
    assert_eq!(
        lines,
        ["src/app.ts:12:10: unsupported process.env read: no declared adapter: process.env.HOME"]
    );
    let source = &APP[..APP.find("export function env").unwrap()];
    let code = ts2py::compile(source, "src/app.ts", &options(host.clone())).unwrap();
    assert!(code.starts_with("# Generated by ts2py (test host) from src/app.ts."));
    assert!(code.contains("from ._ts2py_adapters import cmp_cp, twice\n"));
    // The rebound row: read at call time under mypyc.
    assert!(code.contains("\n@_js_late\ndef make(n):\n"));
    // The contract: a comparator of `cmpCp` is a key sort, not a call per comparison.
    assert!(code.contains("_js_sort_lex("), "{code}");

    // The same row without its contract is an ordinary comparator.
    let mut plain = (*host).clone();
    plain.adapters.rows[1].contract = None;
    let code_plain = ts2py::compile(source, "src/app.ts", &options(Arc::new(plain))).unwrap();
    assert!(!code_plain.contains("_js_sort_lex("));

    // Both answer as JS does, under Python, with the fixture's adapters.
    let python = std::env::var("TS2PY_PYTHON").unwrap_or_else(|_| "python3".to_string());
    for (name, code) in [("lex", &code), ("plain", &code_plain)] {
        let dir = scratch(name);
        let pkg = dir.join("pkg");
        std::fs::create_dir_all(&pkg).unwrap();
        std::fs::write(pkg.join("__init__.py"), "").unwrap();
        std::fs::write(pkg.join("_ts2py_runtime.py"), host.shipped(ts2py::RUNTIME)).unwrap();
        let adapters = host.adapters_module("._ts2py_runtime").unwrap();
        std::fs::write(pkg.join("_ts2py_adapters.py"), host.shipped(&adapters)).unwrap();
        std::fs::write(pkg.join("app.py"), code).unwrap();
        let out = Command::new(&python)
            .arg("-c")
            .arg("import sys; sys.path.insert(0, sys.argv[1]); from pkg import app; print(app.order(['b', 'a', '\\u00e9', 'Z']), app.make(2))")
            .arg(&dir)
            .output()
            .unwrap_or_else(|e| panic!("cannot run {python}: {e} (set TS2PY_PYTHON)"));
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(
            String::from_utf8(out.stdout).unwrap().trim_end(),
            "['Z', 'a', 'b', 'é'] 5",
            "{name}"
        );
        std::fs::remove_dir_all(&dir).unwrap();
    }
}

#[test]
fn the_cli_reads_the_host_file_and_emits_its_adapters_shipped() {
    let dir = scratch("cli");
    let out = dir.join("_ts2py_adapters.py");
    let status = Command::new(env!("CARGO_BIN_EXE_ts2py"))
        .arg("--emit-adapters")
        .arg(&out)
        .arg("--config")
        .arg(fixture())
        .status()
        .unwrap();
    assert!(status.success());
    let text = std::fs::read_to_string(&out).unwrap();
    assert_eq!(
        text,
        "# The test host's adapters (tests/host.rs).\n# Shipped form: see tests/fixtures/host/adapters.py.\nfrom ._ts2py_runtime import _js_num\n\n\n\ndef twice(n):\n    return _js_num(n) * 2\n\n\ndef cmp_cp(a, b):\n    return -1 if a < b else (1 if a > b else 0)\n"
    );
    // No host file: nothing to emit, a usage error.
    let run = Command::new(env!("CARGO_BIN_EXE_ts2py"))
        .arg("--emit-adapters")
        .arg(dir.join("none.py"))
        .output()
        .unwrap();
    assert_eq!(run.status.code(), Some(2));
    assert_eq!(
        String::from_utf8_lossy(&run.stderr),
        "ts2py: --emit-adapters needs --config naming an adapter_source\n"
    );
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn a_malformed_host_file_is_refused_with_its_reason() {
    let base = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/host");
    let row = |extra: &str| {
        format!(
            "adapter_source = \"adapters.py\"\n[[adapter]]\nname = \"f\"\npy_name = \"f\"\n{extra}"
        )
    };
    let cases = [
        (
            row("kind = \"function\"\nwhy = \" \""),
            "adapter f (a global): no why; every row says why it is faithful",
        ),
        (
            row("kind = \"klass\"\nwhy = \"w\""),
            "adapter f (a global): unknown kind klass",
        ),
        (
            row("kind = \"class\"\nwhy = \"w\""),
            "adapter f (a global): kind class needs methods",
        ),
        (
            row("kind = \"function\"\nmethods = []\nwhy = \"w\""),
            "adapter f (a global): kind function takes no methods",
        ),
        (
            row("kind = \"function\"\ncontract = \"fast\"\nwhy = \"w\""),
            "adapter f (a global): unknown contract fast",
        ),
        (
            format!(
                "{}\n{}",
                row("kind = \"function\"\nwhy = \"w\""),
                "[[adapter]]\nname = \"f\"\npy_name = \"g\"\nkind = \"function\"\nwhy = \"w\"\n"
            ),
            "adapter f (a global): declared twice",
        ),
        (
            "[[adapter]]\nname = \"f\"\npy_name = \"f\"\nkind = \"function\"\nwhy = \"w\"\n"
                .to_string(),
            "adapter rows need an adapter_source",
        ),
        (
            "shipped_note = \"not a comment\"\n".to_string(),
            "shipped_note must be one comment line (starting with #)",
        ),
    ];
    for (text, want) in cases {
        assert_eq!(
            ts2py::Host::parse(&text, &base).unwrap_err(),
            want,
            "{text}"
        );
    }
    // An unknown key is a TOML error naming it, not a key silently ignored.
    let err = ts2py::Host::parse("generater = \"x\"\n", &base).unwrap_err();
    assert!(err.contains("generater"), "{err}");
}
