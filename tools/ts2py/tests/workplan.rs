//! The pilot input: runtime-ts/src/workplan.ts compiles, deterministically, to a module that
//! exposes the legacy names and runs under Python with JS semantics.

use std::path::{Path, PathBuf};
use std::process::Command;

/// J85-R2 L2: these tests are the gate, so an interpreter that cannot be started is a failure,
/// never a silent pass. `TS2PY_PYTHON` picks the interpreter; default `python3`.
fn python_missing(python: &str, err: &std::io::Error) -> String {
    format!(
        "cannot run {python}: {err}; this test runs the generated module under Python and fails without one (set TS2PY_PYTHON to an interpreter)"
    )
}

use sha2::{Digest, Sha256};

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .unwrap()
}

fn workplan_source() -> String {
    std::fs::read_to_string(repo().join("runtime-ts/src/workplan.ts")).unwrap()
}

fn compile_workplan(options: &ts2py::Options) -> String {
    ts2py::compile(&workplan_source(), "runtime-ts/src/workplan.ts", options)
        .unwrap_or_else(|lines| panic!("workplan.ts was refused:\n{}", lines.join("\n")))
}

#[test]
fn compiles_with_the_legacy_public_names() {
    let module = compile_workplan(&ts2py::Options::default());
    assert!(module.contains("\n__all__ = [\"plan\", \"touches_refusal\"]\n"));
    assert!(module.contains("\ndef plan(input):\n"));
    assert!(module.contains("\ndef touches_refusal(node_id, touches):\n"));
    // Private helpers carry a leading underscore.
    assert!(module.contains("\ndef _read_nodes(nodes):\n"));
    assert!(module.contains("\ndef _cycle_path(nodes, emitted):\n"));
}

#[test]
fn header_names_the_source_and_its_sha256() {
    let source = workplan_source();
    let hex: String = Sha256::digest(source.as_bytes())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    let module = compile_workplan(&ts2py::Options::default());
    let mut lines = module.lines();
    assert_eq!(
        lines.next().unwrap(),
        "# Generated by tools/ts2py from runtime-ts/src/workplan.ts. DO NOT EDIT: change the TypeScript and regenerate."
    );
    assert_eq!(lines.next().unwrap(), format!("# source-sha256: {hex}"));
}

#[test]
fn deterministic_across_runs_and_working_directories() {
    let a = compile_workplan(&ts2py::Options::default());
    let b = compile_workplan(&ts2py::Options::default());
    assert_eq!(a, b);

    // Through the CLI from two different directories: the header path is repo-relative.
    let dir = std::env::temp_dir().join(format!("ts2py-det-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let input = repo().join("runtime-ts/src/workplan.ts");
    let mut outputs = Vec::new();
    for (i, cwd) in [repo(), repo().join("tools/ts2py")].iter().enumerate() {
        let out = dir.join(format!("w{i}.py"));
        let rel = pathdiff(&input, cwd);
        let status = Command::new(env!("CARGO_BIN_EXE_ts2py"))
            .current_dir(cwd)
            .arg(&rel)
            .arg("-o")
            .arg(&out)
            .status()
            .unwrap();
        assert!(status.success());
        outputs.push(std::fs::read(&out).unwrap());
    }
    assert_eq!(outputs[0], outputs[1]);
    assert_eq!(outputs[0], a.into_bytes());
    std::fs::remove_dir_all(&dir).unwrap();
}

/// `target` relative to `base`, both absolute, for the two layouts this test uses.
fn pathdiff(target: &Path, base: &Path) -> PathBuf {
    let repo = repo();
    let rel = target.strip_prefix(&repo).unwrap();
    let depth = base.strip_prefix(&repo).unwrap().components().count();
    let mut out = PathBuf::new();
    for _ in 0..depth {
        out.push("..");
    }
    out.join(rel)
}

#[test]
fn runtime_module_mode_imports_only_what_it_uses() {
    let options = ts2py::Options {
        runtime_module: Some("._ts2py_runtime".to_string()),
    };
    let module = compile_workplan(&options);
    assert!(module.contains("from ._ts2py_runtime import (  # noqa: F401\n"));
    assert!(module.contains("    _JsMap,\n"));
    assert!(module.contains("    _js_re,\n"));
    assert!(
        !module.contains("def _js_truthy("),
        "the runtime is imported, not inlined"
    );
    assert!(
        !module.contains("    _js_add,\n"),
        "workplan.ts never uses +"
    );
}

/// Run the generated module under Python on a real graph, a hold and a
/// refusal. `TS2PY_PYTHON` picks the interpreter; default `python3`.
#[test]
fn generated_module_runs_under_python() {
    let module = compile_workplan(&ts2py::Options::default());
    let dir = std::env::temp_dir().join(format!("ts2py-run-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("workplan_gen.py");
    std::fs::write(&path, module).unwrap();
    let driver = r#"
import importlib.util, json, sys
spec = importlib.util.spec_from_file_location("w", sys.argv[1])
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
cases = [
    [{"id": "a", "depends_on": []}, {"id": "b", "depends_on": ["a"]}, {"id": "c", "depends_on": [], "priority": 2}],
    [{"id": "a", "depends_on": [], "touches": ["f"]}, {"id": "b", "depends_on": [], "touches": ["f"]}],
    [{"id": "tail", "depends_on": ["b"]}, {"id": "b", "depends_on": ["c"]}, {"id": "c", "depends_on": ["b"]}],
    [{"id": "a", "depends_on": [], "priority": True}],
    [{"id": "a", "depends_on": [], "touches": {"b": [2.5, 3.0], "1": "ไทย"}}],
]
print(json.dumps([m.plan(c) for c in cases], ensure_ascii=False, separators=(",", ":")))
"#;
    let python = std::env::var("TS2PY_PYTHON").unwrap_or_else(|_| "python3".to_string());
    let run = Command::new(&python)
        .arg("-c")
        .arg(driver)
        .arg(&path)
        .output()
        .unwrap_or_else(|err| panic!("{}", python_missing(&python, &err)));
    std::fs::remove_dir_all(&dir).unwrap();
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    let expected = concat!(
        r#"[{"batches":[["c","a"],["b"]],"sequence":["c","a","b"],"width":2},"#,
        r#"{"batches":[["a"],["b"]],"sequence":["a","b"],"width":1,"held":[{"id":"b","batch":0,"by":"a","path":"f"}]},"#,
        r#"{"result":"error","reason":"the graph has a cycle: b -> c -> b"},"#,
        r#"{"result":"error","reason":"nodes[0].priority must be an integer"},"#,
        r#"{"result":"error","reason":"node a touches {\"1\":\"ไทย\",\"b\":[2.5,3]}, which is not a plain relative path"}]"#,
    );
    assert_eq!(String::from_utf8(run.stdout).unwrap().trim_end(), expected);
}
